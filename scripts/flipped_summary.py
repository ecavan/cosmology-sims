"""Flipped-RVM numbers (out/numbers_flipped.tex) and figure (out/figures/fig_flipped.pdf) from stored results."""
import json
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parents[1]
RES, OUT = HERE / "results", HERE / "out"
(OUT / "figures").mkdir(parents=True, exist_ok=True)
real = json.loads((RES / "flipped_fit_pantheon+.json").read_text())
fl = real["flipped"]
load = lambda name: [json.loads(l) for l in open(RES / f"flipped_mocks_{name}.jsonl")]
mL, mC, mF, asim = load("lcdm_a"), load("cpl_a"), load("flipped_a"), load("flipped_asimov")[0]

chi_l, chi_c, chi_f = real["lcdm"]["chi2"], real["cpl"]["chi2"], fl["chi2"]
d_lf, d_lc, d_cf = chi_l - chi_f, chi_l - chi_c, chi_c - chi_f
w0, wa = real["cpl"]["x"][3], real["cpl"]["x"][4]
nu, z1, z2 = fl["x"][3], fl["x"][4], fl["x"][5]

arr = lambda R, f: np.array([f(r) for r in R])
lf_L, lc_L = arr(mL, lambda r: r["chi2_lcdm"] - r["chi2_flipped"]), arr(mL, lambda r: r["chi2_lcdm"] - r["chi2_cpl"])
cf_C, cf_F = arr(mC, lambda r: r["chi2_cpl"] - r["chi2_flipped"]), arr(mF, lambda r: r["chi2_cpl"] - r["chi2_flipped"])
w0F, waF = arr(mF, lambda r: r["w0"]), arr(mF, lambda r: r["wa"])
pval = lambda x, obs: (np.sum(x >= obs) + 1) / (len(x) + 1)  # one-sided, as in make_numbers.py
p_lf, p_lc = pval(lf_L, d_lf), pval(lc_L, d_lc)
p_cfC, p_cfF = pval(cf_C, d_cf), pval(cf_F, d_cf)
slope_real = wa / (1 + w0)

h, wb, wbc_star = fl["x"][0], fl["x"][1], fl["x"][2]
wm0 = wbc_star / ((1 + z1) ** (-6 * nu) * (1 + z2) ** (3 * nu))  # today's ω_bc (p1.models.flipped_early_factor)
om0 = (wm0 + 0.06 / 93.14) / h ** 2                                 # Ω_m today including the neutrino
dip = 100 * (1 - ((1 + z1) / (1 + z2)) ** (3 * nu))                 # % of comoving matter moved into the vacuum by z1
macros = {
    "NflNu": f"{nu:.2f}", "NflZone": f"{z1:.1f}", "NflZtwo": f"{z2:.1f}",
    "NflChi": f"{chi_f:.1f}", "NflAIC": f"{d_lf - 6:.1f}", "NflOm": f"{om0:.4f}", "NflHzero": f"{100 * h:.2f}",
    "NflDip": f"{dip:.0f}",
    "NflGain": f"{100 * (1 / ((1 + z1) ** (-6 * nu) * (1 + z2) ** (3 * nu)) - 1):.0f}",  # % excess of Ω_m a³ today over CMB
    "NflZtrue": f"{(1 + z1) ** 2 / (1 + z2) - 1:.1f}",  # w_eff = −1 where Ω_m a³ regains its CMB value, a = a1²/a2
    "NflDchiL": f"{d_lf:.1f}", "NflDchiCF": f"{d_cf:.1f}",
    "NflAsimWzero": f"{asim['w0']:.3f}", "NflAsimWa": f"{asim['wa']:.2f}",
    "NflAsimSlope": f"{asim['slope']:.1f}", "NflAsimZx": f"{asim['zcross']:.2f}",
    "NflAsimDchi": f"{asim['chi2_lcdm'] - asim['chi2_cpl']:.1f}",
    "NflNmockL": f"{len(mL)}", "NflNmockC": f"{len(mC)}", "NflNmockF": f"{len(mF)}",
    "NflpLF": f"{p_lf:.2f}", "NflpLC": f"{p_lc:.2f}",
    "NflkLF": f"{int(np.sum(lf_L >= d_lf))}", "NflkLC": f"{int(np.sum(lc_L >= d_lc))}",
    "NflMeanLF": f"{lf_L.mean():.1f}", "NflMeanLC": f"{lc_L.mean():.1f}",
    "NflpCFc": f"{p_cfC:.2f}", "NflpCFf": f"{p_cfF:.2f}",
    "NflMockWzero": f"{w0F.mean():.2f}\\pm{w0F.std():.2f}", "NflMockWa": f"{waF.mean():.2f}\\pm{waF.std():.2f}",
}
out = OUT / "numbers_flipped.tex"
out.write_text("% generated by scripts/flipped_summary.py\n" +
               "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
print(out.read_text())

# (a) w0–wa plane; (b) Δχ² of ΛCDM-truth mocks
BLUE, ORANGE, GREY, INK = "#2a78d6", "#eb6834", "#8a8a85", "#1a1a19"
fig, ax = plt.subplots(1, 2, figsize=(10, 4.2))
a = ax[0]
a.scatter(w0F, waF, s=12, color=BLUE, alpha=0.35, lw=0, label="w0wa fits to flipped-RVM mocks")
a.plot(asim["w0"], asim["wa"], "o", color=BLUE, ms=9, mec="white", label="same, noiseless")
x = np.linspace(-1.0, -0.86, 10)
a.plot(x, -8.2 * (1 + x), color=ORANGE, lw=2, label="minimal-RVM track")
a.plot(w0, wa, "*", color=INK, ms=15, label="real data")
a.plot(-1, 0, "+", color=GREY, ms=12, mew=2)
a.annotate("ΛCDM", (-1, 0), (-0.995, 0.08), color=GREY, fontsize=9)
a.set_xlabel("$w_0$"); a.set_ylabel("$w_a$"); a.set_xlim(-1.02, -0.68); a.set_ylim(-1.3, 0.25)
a.legend(fontsize=8, frameon=False, loc="upper right")
a.set_title("(a) What a $w_0w_a$ fit reports", fontsize=10)
b = ax[1]
bins = np.linspace(0, 16, 33)
b.hist(lf_L, bins, color=BLUE, alpha=0.55, label="flipped RVM")
b.hist(lc_L, bins, color=GREY, alpha=0.55, label="$w_0w_a$CDM")
b.axvline(d_lf, color=BLUE, lw=2, ls="--"); b.axvline(d_lc, color=GREY, lw=2, ls="--")
b.text(d_lf + 0.2, b.get_ylim()[1] * 0.9, f"real data\n{d_lf:.1f}", color=BLUE, fontsize=8)
b.text(d_lc - 0.2, b.get_ylim()[1] * 0.9, f"real data\n{d_lc:.1f}", color=GREY, fontsize=8, ha="right")
b.set_xlabel(r"$\Delta\chi^2(\Lambda{\rm CDM}-{\rm model})$ in $\Lambda$CDM mocks")
b.set_ylabel("mocks"); b.legend(fontsize=8, frameon=False, loc="center right")
b.set_title(r"(b) Improvement over $\Lambda$CDM from noise alone", fontsize=10)
for q in ax:
    q.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
for ext in ("pdf", "png"):
    fig.savefig(OUT / "figures" / f"fig_flipped.{ext}", dpi=160)
print("slope_real", round(slope_real, 2))
