"""Figure: the flipped RVM's best fit over fixed switch redshifts (out/figures/fig_flipped_switches.pdf) and macros
(out/numbers_switches.tex), from results/flipped_switch_map_pantheon+.json and results/full_cmb_flipped.jsonl."""
import json
from pathlib import Path

import matplotlib
import matplotlib.ticker
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parents[1]
RES, OUT = HERE / "results", HERE / "out"
d = json.loads((RES / "flipped_switch_map_pantheon+.json").read_text())
G = d["grid"]
c_l, c_c = d["chi2_lcdm"], d["chi2_cpl"]
z1 = np.array([g["z1"] for g in G]); z2 = np.array([g["z2"] for g in G])
nu = np.array([g["nu"] for g in G]); dchi = np.array([g["dchi2_lcdm"] for g in G])
ib = int(np.argmax(dchi))

# full-Planck profiles at fixed switches (minimum over ν by parabola, as in make_numbers.py)
FC = {(1.22, 2.16): "0.074", (1.1, 1.8): "0.095", (2.58, 6.1): "0.016"}

INK, ORANGE = "#1a1a19", "#eb6834"
dz = z2 - z1
OFF = {(1.1, 1.8): (-38, 14), (1.22, 2.16): (12, -16), (2.58, 6.1): (-14, 12)}  # label offsets in points
fig, ax = plt.subplots(1, 2, figsize=(10, 4.0), sharey=True)
for a, val, lab, cmap in ((ax[0], dchi, r"$\Delta\chi^2(\Lambda{\rm CDM}-{\rm flipped})$", "cividis"),
                          (ax[1], nu, r"best-fit $\nu$", "magma_r")):
    sc = a.scatter(z1, dz, c=val, cmap=cmap, vmin=0, s=120, marker="s", lw=0)
    good = dchi >= c_l - c_c
    a.scatter(z1[good], dz[good], s=120, marker="s", facecolor="none", edgecolor=INK, lw=1.3)
    for (p1, p2), v in FC.items():
        a.plot(p1, p2 - p1, "o", ms=8, mfc="none", mec=ORANGE, mew=2)
        if a is ax[1]:
            a.annotate(f"{v}", (p1, p2 - p1), xytext=OFF[(p1, p2)], textcoords="offset points",
                       color=ORANGE, fontsize=9, fontweight="bold")
    cb = fig.colorbar(sc, ax=a, pad=0.02); cb.set_label(lab, fontsize=9)
    a.set_xlabel("$z_1$ (exchange reverses)")
    a.set_yscale("log"); a.set_yticks([0.3, 0.5, 1, 2, 5]); a.set_yticklabels(["0.3", "0.5", "1", "2", "5"])
    a.yaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    a.spines[["top", "right"]].set_visible(False)
ax[0].set_ylabel("$z_2-z_1$ (width of the window)")
ax[0].set_title("(a) Improvement over $\\Lambda$CDM, compressed CMB", fontsize=10)
ax[1].set_title("(b) Best-fit $\\nu$ (orange: full Planck)", fontsize=10)
fig.tight_layout()
for ext in ("pdf", "png"):
    fig.savefig(OUT / "figures" / f"fig_flipped_switches.{ext}", dpi=160)

# macros: the ridge of good fits
f = lambda x, n=1: f"{x:.{n}f}"
near = [g for g in G if g["dchi2_lcdm"] >= dchi.max() - 2.5]
M = {"swBestdchi": f(dchi.max()), "swBestzone": f(z1[ib]), "swBestztwo": f(z2[ib]), "swBestnu": f(nu[ib], 2),
     "swNpts": str(len(G)), "swNear": str(len(near)),
     "swNearnulo": f(min(g["nu"] for g in near), 2), "swNearnuhi": f(max(g["nu"] for g in near), 2),
     "swNearzonehi": f(max(g["z1"] for g in near)), "swNearztwohi": f(max(g["z2"] for g in near)),
     "swNbeat": str(int((dchi >= c_l - c_c).sum())),
     "swMeannu": f([g["nu"] for g in G if (g["z1"], g["z2"]) == (2.6, 6.1)][0], 3),
     "swMeandchi": f([g["dchi2_lcdm"] for g in G if (g["z1"], g["z2"]) == (2.6, 6.1)][0])}
txt = "% generated by scripts/flipped_switch_figure.py — do not edit\n" + "".join(
    f"\\newcommand{{\\N{k}}}{{{v}}}\n" for k, v in M.items())
(OUT / "numbers_switches.tex").write_text(txt)
print(txt)
print("near:", sorted((g["z1"], g["z2"], round(g["nu"], 3), round(g["dchi2_lcdm"], 1)) for g in near))
